const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path');
const { createDatabase, seedCompanies, id, migration, isolationMigration } = require('./helpers/tenant-test-database.cjs');
(async () => {
 const db = await createDatabase();
 try {
  for (const name of fs.readdirSync(path.resolve(__dirname, '../../../supabase/migrations')).filter(n => n.endsWith('.sql') && n > isolationMigration).sort()) await db.exec(migration(name));
  await seedCompanies(db);
  const scalar = async (sql, args=[]) => Object.values((await db.query(sql,args)).rows[0])[0];
  const bind = (company, external, page, actor=id(company*10+1)) => scalar("SELECT bind_social_account($1,$2,'instagram',$3,$4,'Fixture','ciphertext','v26.0')",[id(company),actor,external,page]);
  const disconnect = () => scalar("SELECT configure_social_account($1,$2,'instagram','disconnect',NULL)",[id(1),id(11)]);
  const receive = (account, lead, mid) => scalar("SELECT receive_social_message($1,$2,'777',$3,'Olá','[]',NULL,$4)",[account,id(lead),mid,new Date().toISOString()]);
  const firstAccount = await bind(1,'456','123');
  const first = await receive(firstAccount,701,'first');
  await scalar("SELECT social_handoff($1,$2,$3,'human')",[id(1),id(11),first.threadId]);
  const queued = await scalar("SELECT enqueue_social_batch($1,$2,$3,'old-pending',$4,'human',NULL)",[id(1),first.threadId,id(11),JSON.stringify([{content:'Só pela conta original',media:[]}])]);
  await assert.rejects(() => bind(1,'789','987'), /social_account_disconnect_required/);
  await db.query("UPDATE social_messages SET status='sending' WHERE id=$1",[queued[0]]);
  await assert.rejects(disconnect,/social_sending/);
  await db.query("UPDATE social_messages SET status='pending' WHERE id=$1",[queued[0]]);
  await disconnect();
  assert.equal(await disconnect(),true,'disconnect retry is idempotent');
  assert.equal(await scalar('SELECT token_ciphertext FROM social_accounts WHERE id=$1',[firstAccount]),null);
  assert.equal(await scalar('SELECT status FROM social_messages WHERE id=$1',[queued[0]]),'failed');
  await assert.rejects(() => bind(1,'456','123',null), /social_connection_unavailable/,'legacy env cannot reconnect disabled account');
  await assert.rejects(() => bind(1,'999','888',null), /social_connection_unavailable/,'legacy env cannot create a different account after explicit disconnect');
  const secondAccount = await bind(1,'789','987');
  assert.notEqual(secondAccount, firstAccount);
  const second = await receive(secondAccount,702,'second');
  assert.notEqual(second.threadId,first.threadId,'same scoped recipient on new account has separate conversation');
  assert.notEqual(second.leadId,first.leadId);
  assert.equal(await scalar('SELECT account_id FROM social_threads WHERE id=$1',[first.threadId]),firstAccount,'history remains attached to original account');
  assert.equal(await scalar('SELECT count(*)::int FROM social_accounts WHERE company_id=$1 AND enabled',[id(1)]),1);
  await assert.rejects(() => receive(firstAccount,703,'late-old'),/social_connection_unavailable/);
  assert.equal(await scalar('SELECT claim_social_message($1,$2)',[id(1),queued[0]]),null,'old pending dispatch cannot use new token');
  await assert.rejects(() => bind(2,'456','123'),/social_account_bound/,'other tenant cannot take archived account');
  await assert.rejects(() => bind(2,'789','987'),/social_account_bound/);
  await assert.rejects(() => bind(1,'456','123',id(21)),/social_forbidden/);
  await scalar("SELECT configure_social_account($1,$2,'instagram','mode','suggestions')",[id(1),id(11)]);
  assert.equal(await scalar('SELECT default_mode FROM social_accounts WHERE id=$1',[secondAccount]),'suggestions');
  assert.equal(await scalar('SELECT default_mode FROM social_accounts WHERE id=$1',[firstAccount]),'human','history is never updated by channel preference');
  const inbox=await scalar("SELECT read_social_inbox($1,$2,'instagram')",[id(1),id(11)]);
  assert.equal(inbox.length,2);assert.equal(inbox.find(t=>t.id===first.threadId).enabled,false);assert.equal(inbox.find(t=>t.id===second.threadId).enabled,true);
  await assert.rejects(()=>db.query('UPDATE social_accounts SET enabled=true WHERE id=$1',[firstAccount]),/unique|duplicate/,'database itself enforces one active account');
  await disconnect();
  assert.equal(await bind(1,'456','123'),firstAccount,'reconnecting the original account restores its own immutable identity');
  assert.equal(await scalar('SELECT account_id FROM social_threads WHERE id=$1',[second.threadId]),secondAccount);
  await db.exec('SET ROLE anon');
  await assert.rejects(()=>bind(1,'456','123'),/permission denied/);
  await db.exec('RESET ROLE');
  console.log('PASS social account switch: one active channel, immutable account namespaces, retained history, tenant ownership, queued sends cancelled, in-flight guard, legacy fallback denied and reconnect original identity.');
 } finally { await db.close(); }
})().catch(error=>{console.error(error);process.exit(1);});
